#!/usr/bin/env node
/**
 * Tests for the matrix page.
 *
 * The risk this page carries is not "does it look right" — that is one screenshot
 * away and changes with every restyle. It is **drift**: the page rendering a status
 * the checker no longer agrees with. A cell shown as 验 while its script was deleted
 * is the failure this repo keeps finding, wearing a green dot.
 *
 * So the tests assert agreement with `matrix-check --json`, structure of the grid,
 * and that the inline script parses. Interaction itself (click a cell, filter a
 * chain) is verified separately with a real DOM; wiring a browser or jsdom into CI
 * for it would trade a large dependency for a check the payload comparison already
 * covers at the level that can actually go wrong.
 *
 * Nothing here touches the real docs/site: every build goes through SITE_DIR into a
 * scratch directory, for the reason recorded in build.test.mjs — a concurrent
 * rebuild once silently restored a file another test had just corrupted.
 */
import { test } from 'node:test';
import assert from 'node:assert/strict';
import { mkdtemp, rm, readFile, writeFile } from 'node:fs/promises';
import { execFile } from 'node:child_process';
import { promisify } from 'node:util';
import { tmpdir } from 'node:os';
import { join, resolve, dirname } from 'node:path';
import { fileURLToPath } from 'node:url';

const ROOT = resolve(dirname(fileURLToPath(import.meta.url)), '..', '..');
const exec = promisify(execFile);

/** Build the site into a scratch dir and return the matrix page's HTML. */
async function built() {
  const dir = await mkdtemp(join(tmpdir(), 'matrix-page-'));
  try {
    await exec('node', [join(ROOT, 'scripts/site/build.mjs')], { env: { ...process.env, SITE_DIR: dir } });
    return await readFile(join(dir, 'matrix.html'), 'utf8');
  } finally { await rm(dir, { recursive: true, force: true }); }
}

/** The payload the page renders from, as the page itself would read it. */
function payload(html) {
  const m = /var DATA = (\{[\s\S]*?\});\n/.exec(html);
  assert.ok(m !== null, 'the page carries an inline DATA payload');
  return JSON.parse(m[1]);
}

const data = async () => {
  const { stdout } = await exec('node', [join(ROOT, 'scripts/matrix-check.mjs'), '--json'])
    .catch((e) => ({ stdout: e.stdout }));
  return JSON.parse(stdout);
};

test('the page renders one cell per matrix cell, with unique coordinates', async () => {
  const html = await built();
  const doc = await data();
  const coords = [...html.matchAll(/data-stage="([^"]+)" data-layer="([^"]+)"/g)]
    .map((m) => `${m[1]}\u0000${m[2]}`);
  assert.equal(coords.length, doc.cells.length);
  assert.equal(new Set(coords).size, doc.cells.length, 'two cells share a position');
});

test('every status on the page matches what the checker computed', async () => {
  const html = await built();
  const doc = await data();
  const p = payload(html);
  assert.equal(p.cells.length, doc.cells.length);
  for (const cell of doc.cells) {
    const shown = p.cells.find((c) => c.stage === cell.stage && c.layer === cell.layer);
    assert.ok(shown !== undefined, `${cell.stage} · ${cell.layer} is missing from the page payload`);
    assert.equal(shown.status, cell.status,
      `${cell.stage} · ${cell.layer} renders as ${shown.status} but the checker says ${cell.status}`);
  }
});

test('the page shows the same counts as the checker', async () => {
  const html = await built();
  const doc = await data();
  const verified = Number((/mt-n">(\d+) 格有检查器/.exec(html) ?? [])[1]);
  const contract = Number((/mt-n">(\d+) 格只有契约/.exec(html) ?? [])[1]);
  assert.equal(verified, doc.byStatus.verified ?? 0);
  assert.equal(contract, doc.byStatus.contract ?? 0);
});

test('the inline script is valid JavaScript', async () => {
  const html = await built();
  const m = /<script>\n([\s\S]*?)\n<\/script>/.exec(html);
  assert.ok(m !== null, 'the page has one inline script');
  const dir = await mkdtemp(join(tmpdir(), 'matrix-js-'));
  try {
    const file = join(dir, 'inline.js');
    await writeFile(file, m[1], 'utf8');
    await exec('node', ['--check', file]);   // exits non-zero on a syntax error
  } finally { await rm(dir, { recursive: true, force: true }); }
});

test('no template marker or placeholder survived into the output', async () => {
  const html = await built();
  for (const marker of ['__DATA__', '{css}', '{js}', 'None', 'undefined']) {
    assert.ok(!html.includes(marker), `the page still contains "${marker}"`);
  }
});

test('the page works without JS: all content is in the markup, not generated by script', async () => {
  const html = await built();
  const doc = await data();
  // The three thing are what a reader comes for. If they only appear after a click,
  // the page shows nothing to a printout — so they must be reachable from the payload
  // that is itself in the markup, and the grid must be server-rendered.
  for (const cell of doc.cells) {
    assert.ok(html.includes(cell.output.slice(0, 20).replace(/[&<>]/g, '') || cell.layer),
      `${cell.stage} · ${cell.layer}'s output is not present in the served HTML`);
  }
  // The grid cells themselves are in the markup (no JS needed to see the shape).
  assert.equal((html.match(/class="mt-cell /g) ?? []).length, doc.cells.length);
});

test('the column order is the declared layer order, not the order cells happen to appear', async () => {
  /*
   * Caught by a screenshot, not by any test here: the grid derived its columns with
   * `dict.fromkeys` over cells sorted by stage, so 需求's two layers (指标, 结论) came
   * first and the table read as 指标·结论·采集·存储·… — as if the pipeline began at
   * the metric layer. The order is a fact about the layers; it must come from the
   * place that declares them.
   */
  const html = await built();
  const doc = await data();
  const head = /<thead>(.*?)<\/thead>/.exec(html)[1];
  // Drop the first (empty) header, which is the row-label column.
  const shown = [...head.matchAll(/<th scope="col">([^<]*)<\/th>/g)].map((m) => m[1]).filter((h) => h !== '');
  assert.deepEqual(shown, doc.layers, "column order must equal matrix.json's layers");
});
